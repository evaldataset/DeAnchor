"""설명 품질 평가 (LLM-as-Judge).

GPT-4o 또는 로컬 LLM을 심판으로 사용하여
설명의 정확성, 완전성, 명확성, 실행가능성을 5점 척도로 평가.
"""

import argparse
import json
import os
from pathlib import Path

RESULTS_DIR = Path(__file__).resolve().parent.parent / "experiments" / "results"

JUDGE_SYSTEM_PROMPT = """You are an expert evaluator assessing the quality of financial fraud explanations generated by an AI system. Rate each explanation on 4 dimensions using a 1-5 scale.

Rating Scale:
1 = Very Poor: Completely wrong or irrelevant
2 = Poor: Major errors or missing key information
3 = Adequate: Generally correct but lacks depth
4 = Good: Accurate and useful with minor gaps
5 = Excellent: Comprehensive, accurate, and actionable"""

JUDGE_PROMPT_BLIND = """Evaluate the following fraud explanation. You do NOT know whether this transaction is actually fraudulent — judge the explanation's quality on its own merits.

## Transaction
{transaction_text}

## AI-Generated Explanation
{explanation}

## Evaluation Criteria
Rate each dimension 1-5:

1. **Coherence**: Is the reasoning logical and internally consistent?
2. **Completeness**: Does the explanation address all relevant transaction aspects?
3. **Clarity**: Is the explanation clear, well-structured, and easy to understand?
4. **Actionability**: Does it provide useful guidance for a fraud investigator?

Respond in JSON:
```json
{{
    "coherence": 1-5,
    "completeness": 1-5,
    "clarity": 1-5,
    "actionability": 1-5,
    "overall": 1-5,
    "strengths": ["..."],
    "weaknesses": ["..."],
    "reasoning": "Brief justification"
}}
```"""

JUDGE_PROMPT_WITH_GT = """Evaluate the following fraud explanation against ground truth.

## Transaction
{transaction_text}

## Ground Truth
- Actually fraudulent: {is_fraud}
- ML fraud score: {ml_score:.4f}

## AI-Generated Explanation
{explanation}

## Evaluation Criteria
Rate each dimension 1-5:

1. **Accuracy**: Are the stated patterns and anomalies factually correct given the ground truth?
2. **Completeness**: Does the explanation cover all relevant suspicious aspects?
3. **Clarity**: Is the explanation clear, well-structured, and easy to understand?
4. **Actionability**: Does it provide useful guidance for a fraud investigator?

Respond in JSON:
```json
{{
    "accuracy": 1-5,
    "completeness": 1-5,
    "clarity": 1-5,
    "actionability": 1-5,
    "overall": 1-5,
    "strengths": ["..."],
    "weaknesses": ["..."],
    "reasoning": "Brief justification"
}}
```"""


def evaluate_with_openai(
    transaction_text: str,
    explanation: str,
    is_fraud: bool,
    ml_score: float,
    model: str = "gpt-4o",
) -> dict:
    """OpenAI GPT-4o를 Judge로 사용."""
    try:
        from openai import OpenAI
    except ImportError:
        return {"error": "openai package not installed. pip install openai"}

    api_key = os.environ.get("OPENAI_API_KEY")
    if not api_key:
        return {"error": "OPENAI_API_KEY not set"}

    client = OpenAI(api_key=api_key)

    prompt = JUDGE_PROMPT_WITH_GT.format(
        transaction_text=transaction_text,
        is_fraud="Yes" if is_fraud else "No",
        ml_score=ml_score,
        explanation=json.dumps(explanation, indent=2) if isinstance(explanation, dict) else explanation,
    )

    response = client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
            {"role": "user", "content": prompt},
        ],
        temperature=0.0,
        response_format={"type": "json_object"},
    )

    try:
        return json.loads(response.choices[0].message.content)
    except json.JSONDecodeError:
        return {"raw_response": response.choices[0].message.content, "parse_error": True}


def evaluate_with_local_llm(
    transaction_text: str,
    explanation: str,
    is_fraud: bool,
    ml_score: float,
    llm=None,
) -> dict:
    """로컬 LLM을 Judge로 사용."""
    if llm is None:
        from llm_explainer.llm_inference import LLMInference
        llm = LLMInference()
        llm.load()

    prompt = JUDGE_PROMPT_WITH_GT.format(
        transaction_text=transaction_text,
        is_fraud="Yes" if is_fraud else "No",
        ml_score=ml_score,
        explanation=json.dumps(explanation, indent=2) if isinstance(explanation, dict) else explanation,
    )

    return llm.generate_json(prompt, JUDGE_SYSTEM_PROMPT)


def evaluate_batch(
    predictions_path: str,
    judge_model: str = "gpt-4o",
    max_samples: int | None = None,
) -> dict:
    """배치 평가 실행."""
    with open(predictions_path) as f:
        predictions = [json.loads(line) for line in f]

    if max_samples:
        predictions = predictions[:max_samples]

    print(f"Evaluating {len(predictions)} explanations with {judge_model}...")

    scores = {"accuracy": [], "completeness": [], "clarity": [], "actionability": [], "overall": []}
    results = []

    for i, pred in enumerate(predictions):
        tx = pred.get("original", {})
        explanation = pred.get("anomaly_explanation", {})

        if not explanation or explanation.get("parse_error"):
            continue

        print(f"  [{i + 1}/{len(predictions)}]", end=" ")

        if judge_model.startswith("gpt"):
            eval_result = evaluate_with_openai(
                tx.get("text", ""),
                explanation,
                tx.get("is_fraud", False),
                pred.get("ml_score", 0),
                model=judge_model,
            )
        else:
            eval_result = evaluate_with_local_llm(
                tx.get("text", ""),
                explanation,
                tx.get("is_fraud", False),
                pred.get("ml_score", 0),
            )

        if "error" in eval_result:
            print(f"Error: {eval_result['error']}")
            continue

        for dim in scores:
            if dim in eval_result:
                scores[dim].append(eval_result[dim])

        results.append({"prediction": pred, "evaluation": eval_result})
        print(f"Score: {eval_result.get('overall', 'N/A')}/5")

    # 집계
    summary = {}
    for dim, vals in scores.items():
        if vals:
            summary[dim] = {
                "mean": sum(vals) / len(vals),
                "min": min(vals),
                "max": max(vals),
                "count": len(vals),
            }

    print(f"\n=== Evaluation Summary ({len(results)} samples) ===")
    for dim, stats in summary.items():
        print(f"  {dim:15s}: {stats['mean']:.2f} (range: {stats['min']}-{stats['max']})")

    # 결과 저장
    output_path = RESULTS_DIR / "evaluation_results.json"
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump({"summary": summary, "results": results}, f, indent=2, ensure_ascii=False)
    print(f"\nResults saved to {output_path}")

    return summary


def main():
    parser = argparse.ArgumentParser(description="Evaluate explanation quality")
    parser.add_argument("--predictions", type=str, required=True, help="Predictions JSONL")
    parser.add_argument("--judge_model", type=str, default="gpt-4o")
    parser.add_argument("--max_samples", type=int, default=None)
    args = parser.parse_args()

    evaluate_batch(args.predictions, args.judge_model, args.max_samples)


if __name__ == "__main__":
    main()
